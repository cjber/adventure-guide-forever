#!/usr/bin/env python3
"""Emit Data/Territory.lua: each map's faction territory, for the Library books journey (stdlib only).

A book's stop belongs to the territory of the zone it lies in. The client's AreaTable.FactionGroupMask says whose
territory an area is: 2 Alliance, 4 Horde, 0 contested, and a mask naming both (6) belongs to both. This reads the
whole-map UiMapAssignment of every map Data/Geometry.lua places and pins that area's mask, so a map's territory is
the client's answer rather than a hand-written list. 0 is contested and belongs to either faction's journey.
"""

import re

from forever_tools import fsio
from gen_quests import BUILD, ROOT, db2, run, source_options

OUTPUT = ROOT / "Data" / "Territory.lua"
GEOMETRY = ROOT / "Data" / "Geometry.lua"


def map_ids(text):
    """The uiMap IDs of Data/Geometry.lua's `maps` table."""
    block = re.search(r"^\tmaps = \{\n(.*?)^\t\},", text, re.MULTILINE | re.DOTALL)
    if not block:
        raise ValueError("Data/Geometry.lua has no maps table")
    return sorted(int(ui_map) for ui_map in re.findall(r"^\t\t\[(\d+)\] = ", block[1], re.MULTILINE))


def territory(maps, assignments, areas):
    """Each map -> its area's FactionGroupMask, from the whole-map assignment (WMODoodadPlacementID 0)."""
    area_of = {}
    for row in assignments:
        ui_map = int(row["UiMapID"])
        if ui_map in maps and int(row["WMODoodadPlacementID"]) == 0 and ui_map not in area_of:
            area_of[ui_map] = int(row["AreaID"])
    masks = {int(row["ID"]): int(row["FactionGroupMask"]) for row in areas}
    return {ui_map: masks[area] for ui_map, area in area_of.items() if area in masks}


def render(territories):
    lines = [
        "-- Generated by tools/gen_territory.py: do not edit.",
        f"-- wago.tools UiMapAssignment and AreaTable at {BUILD}.",
        "-- Each map's faction territory from AreaTable.FactionGroupMask: 2 Alliance, 4 Horde, 0 contested, 6 both.",
        "-- A journey keeps its own faction's zones and the contested ones, never the other faction's.",
        "---@type string, AGFNamespace",
        "local _, ns = ...",
        "-- stylua: ignore",
        "ns.Data.territory = {",
    ]
    lines.extend(f"\t[{ui_map}] = {mask}," for ui_map, mask in territories.items())
    return "\n".join([*lines, "}", ""])


def main():
    options = source_options(__doc__)
    maps = map_ids(GEOMETRY.read_text(encoding="utf-8"))
    territories = territory(
        set(maps),
        db2("UiMapAssignment", ("ID", "UiMapID", "AreaID", "WMODoodadPlacementID"), **options),
        db2("AreaTable", ("ID", "FactionGroupMask"), **options),
    )
    if not territories:
        raise ValueError("no map territories; leaving existing output untouched")
    fsio.atomic_write(OUTPUT, render(territories))
    print(f"{len(territories)} of {len(maps)} maps have a territory")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    run(main, "gen_territory")
