#!/usr/bin/env python3
"""The quest XP fills, Data/XPFills.lua, from the forever-db zip (stdlib only).

QuestieDB's Forever records leave some quests without an XP, and the planner paces only a quest it can value
(Planning/Model.lua's QuestXP). forever-db, the Polestar project's published quest database, records the XP the
Forever server answers for each quest: this bundles those numbers as ns.Data.xpfills, one row per quest the zip
carries with an XP above zero. The runtime decides where a fill applies, so the table carries every row and is
never filtered against the test corpus; QuestieSource.lua applies one only where QuestieDB gives no XP.

The zip is cached in tools/.cache, keyed by the pin's sha256, and its checksum is verified against fdb_pin.py
before anything is read. --refresh redownloads, --offline uses the cache only. The database is GPL-3.0 (facts)
and Polestar's own layer is CC BY 4.0; every input's credit is in its NOTICE.md, and THIRD_PARTY.md names what
this addon reads from it.
"""

import hashlib
import io
import json
import zipfile

import fdb_pin
import gen_quests

ROOT = gen_quests.ROOT
OUTPUT = ROOT / "Data" / "XPFills.lua"
# The release's quest records: one JSON object per quest.
QUEST_DATA = "forever-db/data/quest.jsonl"


def verify(content: bytes) -> None:
    digest = hashlib.sha256(content).hexdigest()
    if digest != fdb_pin.FDB_SHA256:
        raise ValueError(f"forever-db {fdb_pin.FDB_TAG}: sha256 {digest} does not match the pin")


def fills(content: bytes) -> dict[int, int]:
    """Every quest the zip carries with an XP above zero, keyed by quest ID."""
    values = {}
    with zipfile.ZipFile(io.BytesIO(content)) as archive:
        for line in archive.read(QUEST_DATA).decode("utf-8").splitlines():
            if not line.strip():
                continue
            quest = json.loads(line)
            xp = quest.get("xp")
            if isinstance(xp, (int, float)) and xp > 0:
                values[int(quest["id"])] = int(xp)
    return values


def render(rows: dict[int, int]) -> str:
    lines = [
        "-- Generated by tools/gen_xpfills.py: do not edit.",
        f"-- forever-db {fdb_pin.FDB_TAG}: the Polestar project's published quest database, which records the XP",
        "-- the Forever server answers for each quest. The zip's sha256:",
        f"-- {fdb_pin.FDB_SHA256}",
        "-- The database is GPL-3.0 (facts) and Polestar's own layer is CC BY 4.0; its NOTICE.md credits every",
        "-- input, and THIRD_PARTY.md names what this addon reads from it.",
        "-- QuestieDB's Forever records leave some quests without an XP, and the planner paces only a quest it",
        "-- can value (Planning/Model.lua's QuestXP): the runtime applies one of these numbers only where",
        "-- QuestieDB gives no XP (QuestieSource.lua), so the table carries every row.",
        "---@type string, AGFNamespace",
        "local _, ns = ...",
        "-- stylua: ignore",
        "ns.Data.xpfills = {",
    ]
    lines.extend(f"\t[{id_}] = {xp}," for id_, xp in sorted(rows.items()))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    options = gen_quests.source_options(__doc__)
    name = f"fdb-{fdb_pin.FDB_SHA256}.zip"
    content = gen_quests.download(fdb_pin.FDB_URL, name, **options)
    try:
        verify(content)
    except ValueError:
        if options.get("offline"):
            raise
        # A changed or corrupted cached zip: redownload once, then hold the pin.
        content = gen_quests.download(fdb_pin.FDB_URL, name, refresh=True, offline=False)
        verify(content)
    rows = fills(content)
    OUTPUT.write_text(render(rows), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(rows):,} rows)")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
        raise SystemExit(f"gen_xpfills: {error}") from error
